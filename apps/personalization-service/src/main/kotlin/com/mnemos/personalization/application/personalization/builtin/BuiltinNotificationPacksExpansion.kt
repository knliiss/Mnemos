                ),
            booster =
                template(
                    emoji = emoji,
                    title = boosterTitle,
                    body = "$voice: {player} активировал {booster}.",
                    compact = "{booster} · {player}",
                    aggregateTitle = "$boosterTitle · несколько активаций",
                ),
            dungeon =
                template(
                    emoji = emoji,
                    title = dungeonTitle,
                    body = "$voice: доступно {dungeon}.",
                    compact = "{dungeon} открыто",
                    aggregateTitle = "$dungeonTitle · несколько окон",
                ),
            raid =
                template(
                    emoji = emoji,
                    title = raidTitle,
                    body = "$voice. Локации: {locations}.",
                    compact = "Рейд → {locations}",
