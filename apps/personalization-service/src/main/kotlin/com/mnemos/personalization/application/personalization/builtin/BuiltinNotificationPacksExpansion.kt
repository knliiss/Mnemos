        key: String,
        name: String,
        price: Long,
        emoji: String,
        voice: String,
        itemTitle: String,
        boosterTitle: String,
        dungeonTitle: String,
        raidTitle: String,
        globalTitle: String,
    ): BuiltinPersonalizationDefinition =
        definition(
            key = "notification.$key",
            name = name,
            pricePrime = price,
            mixedAggregateTitle = "$voice: сразу несколько событий",
            itemDrop =
                template(
                    emoji = emoji,
                    title = itemTitle,
                    body = "$voice: {player} получил «{item}».",
                    compact = "{player} → «{item}»",
