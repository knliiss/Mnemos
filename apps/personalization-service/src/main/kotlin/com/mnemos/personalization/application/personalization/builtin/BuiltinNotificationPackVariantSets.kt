    private fun item(
        id: String,
        rarity: String,
        itemType: String?,
        emoji: String,
        title: String,
        body: String,
    ): NotificationTemplateVariant =
        variant(
            id = id,
            conditions =
                buildList {
                    add(condition(NotificationPackVariantField.ITEM_RARITY, rarity))
                    itemType?.let { add(condition(NotificationPackVariantField.ITEM_TYPE, it)) }
                },
            emoji = emoji,
            title = title,
            body = body,
            compact = title,
            aggregateTitle = title,
        )

    private fun booster(
        id: String,
        value: String,
        emoji: String,
        title: String,
        body: String,
    ): NotificationTemplateVariant =
        variant(
            id = id,
            conditions = listOf(condition(NotificationPackVariantField.BOOSTER, value)),
            emoji = emoji,
            title = title,
            body = body,
            compact = title,
            aggregateTitle = title,
        )

    private fun dungeon(
        id: String,
        value: String,
        emoji: String,
        title: String,
