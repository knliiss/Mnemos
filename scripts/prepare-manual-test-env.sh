#!/usr/bin/env sh
set -eu

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
ROOT_ENV="${1:-}"
MINI_APP_ENV="${2:-apps/mini-app/.env.local}"

if [ -z "$ROOT_ENV" ]; then
    echo "Usage: $0 <root-env-file> [mini-app-env-file]" >&2
    exit 2
fi

if [ ! -f "$ROOT_ENV" ]; then
    echo "Root environment file does not exist: $ROOT_ENV" >&2
    exit 1
fi

read_env_value() {
    env_file="$1"
    key="$2"

    awk -v key="$key" '
        index($0, key "=") == 1 {
            value = substr($0, length(key) + 2)
        }
        END {
            print value
        }
    ' "$env_file"
}

normalize_value() {
    printf '%s' "$1" |
        sed \
            -e 's/\r$//' \
            -e 's/^[[:space:]]*//' \
            -e 's/[[:space:]]*$//' \
            -e 's/^"//' \
            -e 's/"$//' \
            -e "s/^'//" \
            -e "s/'$//"
}

require_https_origin() {
    key="$1"
    value="$(normalize_value "$(read_env_value "$ROOT_ENV" "$key")")"

    if [ -z "$value" ]; then
        echo "Manual test environment requires $key" >&2
        exit 1
    fi

    case "$value" in
        https://*)
            ;;
        *)
            echo "$key must use https:// for Telegram manual testing" >&2
            exit 1
            ;;
    esac

    value="${value%/}"
    authority="${value#https://}"

    case "$authority" in
        */*)
            echo "$key must be an origin without a path: $value" >&2
            exit 1
            ;;
    esac

    case "$authority" in
        example.com|*.example.com)
            echo "$key still points to a placeholder domain: $value" >&2
            exit 1
            ;;
    esac

    printf '%s' "$value"
}

sh "$SCRIPT_DIR/validate-compose-secrets.sh" "$ROOT_ENV"

FRONTEND_ORIGIN="$(require_https_origin MNEMOS_FRONTEND_ORIGIN)"
API_ORIGIN="$(require_https_origin MNEMOS_API_ORIGIN)"
AUTH_ORIGIN="$(require_https_origin MNEMOS_AUTH_ORIGIN)"
TELEGRAM_MAX_AGE="$(normalize_value "$(read_env_value "$ROOT_ENV" MNEMOS_TELEGRAM_INIT_DATA_MAX_AGE_SECONDS)")"

if [ -z "$TELEGRAM_MAX_AGE" ]; then
    TELEGRAM_MAX_AGE=300
fi

case "$TELEGRAM_MAX_AGE" in
    *[!0-9]*|"")
        echo "MNEMOS_TELEGRAM_INIT_DATA_MAX_AGE_SECONDS must be a positive integer" >&2
        exit 1
        ;;
esac

if [ "$TELEGRAM_MAX_AGE" -le 0 ]; then
    echo "MNEMOS_TELEGRAM_INIT_DATA_MAX_AGE_SECONDS must be greater than zero" >&2
    exit 1
fi

FRONTEND_AUTHORITY="${FRONTEND_ORIGIN#https://}"
FRONTEND_HOST="${FRONTEND_AUTHORITY%%:*}"

mkdir -p "$(dirname "$MINI_APP_ENV")"
TEMP_ENV="$(mktemp "${MINI_APP_ENV}.tmp.XXXXXX")"
trap 'rm -f "$TEMP_ENV"' EXIT HUP INT TERM

cat >"$TEMP_ENV" <<EOF
# Generated by scripts/prepare-manual-test-env.sh. Do not commit.
VITE_KEYCLOAK_URL=$AUTH_ORIGIN
VITE_KEYCLOAK_REALM=mnemos
VITE_KEYCLOAK_CLIENT_ID=mnemos-mini-app
VITE_API_URL=$API_ORIGIN
VITE_TELEGRAM_INIT_DATA_MAX_AGE_SECONDS=$TELEGRAM_MAX_AGE
VITE_DEV_ALLOWED_HOST=$FRONTEND_HOST
EOF

mv "$TEMP_ENV" "$MINI_APP_ENV"
trap - EXIT HUP INT TERM

printf 'Manual test environment validated\n'
printf 'Mini App runtime env: %s\n' "$MINI_APP_ENV"
printf 'Telegram frontend origin: %s\n' "$FRONTEND_ORIGIN"
